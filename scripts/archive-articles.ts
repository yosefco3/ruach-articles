/**
 * archive-articles — export EVERY published article from production into a standalone
 * archive repository (markdown + original HTML + images + attachments + raw JSON), and
 * generate shared/retiredArticles.ts so the old URLs 301 instead of 404 once the rows
 * are deleted from the server.
 *
 * Usage: pnpm archive:articles                      → ~/Desktop/ruach-way-articles
 *        pnpm archive:articles --out <dir>
 *        RUACH_BASE_URL=... pnpm archive:articles
 *
 * Read-only against production (public tRPC GETs). Deletion is a separate, explicit
 * script: scripts/delete-archived-articles.ts.
 */
import fs from "fs";
import path from "path";
import os from "os";
import {
  articleToMarkdownFile,
  type ArticleFull,
  type ArticleMeta,
} from "./sync-articles";

const BASE_URL = process.env.RUACH_BASE_URL ?? "https://ruachwisdom.org";
const CONCURRENCY = 4;

type Attachment = { id: number; fileName: string; fileUrl: string; fileSize?: number };
type Comment = { id: number; body: string; authorName?: string | null; createdAt: string };
type ArticleWithFiles = ArticleFull & { attachments?: Attachment[] };

// ── pure helpers (tested) ────────────────────────────────────────────────────

/** Absolute URL for a stored asset: R2 URLs stay, "/uploads/…" gets the site origin. */
export function absoluteAssetUrl(src: string, baseUrl: string): string {
  if (/^https?:\/\//i.test(src)) return src;
  if (src.startsWith("/")) return baseUrl.replace(/\/$/, "") + src;
  return src;
}

/** Stable local file name for an asset URL: last path segment, decoded, de-duplicated by a short hash. */
export function assetFileName(url: string): string {
  let last = url.split("?")[0].split("#")[0].split("/").filter(Boolean).pop() ?? "asset";
  try { last = decodeURIComponent(last); } catch { /* keep raw */ }
  last = last.replace(/[^\p{L}\p{N}._-]+/gu, "_").slice(-120) || "asset";
  let h = 0;
  for (const ch of url) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const dot = last.lastIndexOf(".");
  const stem = dot > 0 ? last.slice(0, dot) : last;
  const ext = dot > 0 ? last.slice(dot) : "";
  return `${stem}-${h.toString(16).slice(0, 6)}${ext}`;
}

/** Every <img src> plus the cover image, as absolute URLs (deduplicated, in order). */
export function collectImageUrls(html: string, coverImage: string | null | undefined, baseUrl: string): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  const push = (u: string | null | undefined) => {
    if (!u) return;
    const abs = absoluteAssetUrl(u.trim(), baseUrl);
    if (!/^https?:\/\//i.test(abs) || abs.startsWith("data:")) return;
    if (!seen.has(abs)) { seen.add(abs); out.push(abs); }
  };
  push(coverImage);
  for (const m of html.matchAll(/<img\b[^>]*\bsrc\s*=\s*"([^"]+)"/gi)) push(m[1]);
  return out;
}

/** Rewrite asset references in text to the archive's relative paths. */
export function rewriteAssetRefs(text: string, mapping: Map<string, string>, baseUrl: string): string {
  let out = text;
  for (const [abs, rel] of mapping) {
    out = out.split(abs).join(rel);
    // the same asset may appear site-relative in the body
    if (abs.startsWith(baseUrl)) out = out.split(abs.slice(baseUrl.length)).join(rel);
  }
  return out;
}

/** The TypeScript module that makes the old URLs redirect (kept in the app repo). */
export function renderRetiredModule(slugs: string[], exportedAt: string): string {
  const sorted = [...new Set(slugs)].sort();
  return [
    "/**",
    " * Articles that were exported to the archive repo and removed from the server",
    " * (site pivot, " + exportedAt + "). Generated by scripts/archive-articles.ts — do not edit.",
    " * /article/<slug> for any of these 301s to RETIRED_ARTICLE_TARGET once the slug no longer",
    " * resolves in the DB, so search results and external links keep landing somewhere useful.",
    " */",
    "export const RETIRED_ARTICLE_TARGET = \"/derech\";",
    "",
    "export const RETIRED_ARTICLE_SLUGS: ReadonlySet<string> = new Set([",
    ...sorted.map((s) => `  ${JSON.stringify(s)},`),
    "]);",
    "",
    "export function isRetiredArticle(slug: string): boolean {",
    "  return RETIRED_ARTICLE_SLUGS.has(slug);",
    "}",
    "",
  ].join("\n");
}

export function buildArchiveReadme(articles: ArticleMeta[], exportedAt: string, baseUrl: string): string {
  const byCategory = new Map<string, ArticleMeta[]>();
  for (const a of articles) byCategory.set(a.category, [...(byCategory.get(a.category) ?? []), a]);
  const lines = [
    "# ארכיון המאמרים — ruachwisdom.org",
    "",
    `ייצוא מלא של ${articles.length} המאמרים שפורסמו באתר עד ${exportedAt}, לפני שהאתר הפך לאתר שיטת "דרך הרוח".`,
    "",
    "| תיקייה | תוכן |",
    "|---|---|",
    "| `articles/` | כל מאמר כ-markdown עם frontmatter (כותרת, slug, קטגוריה, תגיות, תאריכים) |",
    "| `html/` | גוף המאמר המקורי מהעורך (HTML) — להדבקה חוזרת בעורך עשיר |",
    "| `images/` | תמונות השער והתמונות שבגוף המאמרים |",
    "| `attachments/` | קבצים מצורפים |",
    "| `data/articles.json` | כל השורות הגולמיות + תגובות — לשחזור מלא |",
    "",
    `הכתובות המקוריות (\`${baseUrl}/article/<slug>\`) מפנות היום לדף השיטה.`,
    "",
  ];
  for (const [category, list] of byCategory) {
    lines.push(`## ${category}`, "");
    list.sort((x, y) => String(x.createdAt).localeCompare(String(y.createdAt)));
    for (const a of list) {
      lines.push(`- [${a.title}](articles/${encodeURIComponent(a.slug)}.md) (${String(a.createdAt).slice(0, 10)})`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

// ── fetching ─────────────────────────────────────────────────────────────────

async function trpcGet<T>(proc: string, input?: unknown): Promise<T> {
  const qs = input === undefined ? "" : `?input=${encodeURIComponent(JSON.stringify({ json: input }))}`;
  const res = await fetch(`${BASE_URL}/api/trpc/${proc}${qs}`);
  if (!res.ok) throw new Error(`${proc} → HTTP ${res.status}`);
  const payload = (await res.json()) as { result?: { data?: { json?: T } } };
  const data = payload.result?.data?.json;
  if (data === undefined) throw new Error(`${proc} → unexpected response shape`);
  return data;
}

async function mapWithConcurrency<I, O>(items: I[], limit: number, fn: (item: I) => Promise<O>): Promise<O[]> {
  const out: O[] = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) { const i = next++; out[i] = await fn(items[i]); }
    }),
  );
  return out;
}

async function download(url: string, dest: string): Promise<boolean> {
  if (fs.existsSync(dest)) return true;
  const res = await fetch(url);
  if (!res.ok) { console.warn(`  ! ${url} → HTTP ${res.status}`); return false; }
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  return true;
}

async function main() {
  const outIdx = process.argv.indexOf("--out");
  const OUT = path.resolve(outIdx > -1 ? process.argv[outIdx + 1] : path.join(os.homedir(), "Desktop", "ruach-way-articles"));
  for (const d of ["articles", "html", "images", "attachments", "data"]) fs.mkdirSync(path.join(OUT, d), { recursive: true });

  console.log(`Archiving from ${BASE_URL} → ${OUT}`);
  const list = await trpcGet<ArticleMeta[]>("articles.list");
  console.log(`Found ${list.length} published articles; fetching bodies + comments …`);

  const full = await mapWithConcurrency(list, CONCURRENCY, async (a) => {
    const art = await trpcGet<ArticleWithFiles | null>("articles.bySlug", { slug: a.slug });
    const comments = art ? await trpcGet<Comment[]>("comments.list", { articleId: art.id }).catch(() => []) : [];
    return art ? { ...art, comments } : null;
  });

  const raw: unknown[] = [];
  const slugs: string[] = [];
  let images = 0, files = 0, missing = 0;
  for (const a of full) {
    if (!a) continue;
    slugs.push(a.slug);
    raw.push(a);

    // images (cover + inline) → images/, rewritten to relative paths
    const mapping = new Map<string, string>();
    for (const url of collectImageUrls(a.body, a.coverImage, BASE_URL)) {
      const name = assetFileName(url);
      const ok = await download(url, path.join(OUT, "images", name));
      if (ok) { mapping.set(url, `../images/${name}`); images++; } else missing++;
    }
    // attachments → attachments/
    for (const att of a.attachments ?? []) {
      const url = absoluteAssetUrl(att.fileUrl, BASE_URL);
      const name = assetFileName(url);
      const ok = await download(url, path.join(OUT, "attachments", name));
      if (ok) { mapping.set(url, `../attachments/${name}`); files++; } else missing++;
    }

    const body = rewriteAssetRefs(a.body, mapping, BASE_URL);
    const cover = a.coverImage ? rewriteAssetRefs(absoluteAssetUrl(a.coverImage, BASE_URL), mapping, BASE_URL) : null;
    const md = articleToMarkdownFile({ ...a, body, coverImage: cover }, BASE_URL);
    const coverLine = cover ? `![תמונת שער](${cover})\n\n` : "";
    fs.writeFileSync(path.join(OUT, "articles", `${a.slug}.md`), md.replace(/\n# /, `\n${coverLine}# `));
    fs.writeFileSync(path.join(OUT, "html", `${a.slug}.html`),
      `<!-- ${a.title} · ${BASE_URL}/article/${a.slug} -->\n${cover ? `<!-- cover: ${cover} -->\n` : ""}${body}\n`);
    process.stdout.write(".");
  }
  console.log("");

  const exportedAt = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(path.join(OUT, "data", "articles.json"), JSON.stringify(raw, null, 2));
  fs.writeFileSync(path.join(OUT, "README.md"), buildArchiveReadme(list, exportedAt, BASE_URL));

  const retiredPath = path.resolve(import.meta.dirname, "..", "shared", "retiredArticles.ts");
  fs.writeFileSync(retiredPath, renderRetiredModule(slugs, exportedAt));

  console.log(`Wrote ${slugs.length} articles, ${images} images, ${files} attachments (${missing} downloads failed).`);
  console.log(`Retired-slug module: ${path.relative(process.cwd(), retiredPath)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  main().catch((err) => { console.error(err); process.exit(1); });
}
