import { generateText } from "./_core/aiProvider";

export interface TarotAiCard {
  /** שם אפקטיבי (override מה-DB או ברירת המחדל מ-shared). */
  name: string;
  /** שורת מהות קצרה מה-DB (יכולה להיות ריקה). */
  summary: string;
  /** הפירוש הסטטי כ-plain text (הקליינט ממיר מ-HTML). */
  text: string;
}

export interface TarotAiContext {
  /** יכולה להיות ריקה — שליפה בלי שאלה מותרת (קריאה כללית). */
  question: string;
  /** בדיוק 3, בסדר השליפה. */
  cards: TarotAiCard[];
}

/**
 * בונה את פרומפט קריאת הפריסה. טהורה — בלי רשת, בלי env.
 * שיטת הקריאה (החלטת 2026-09-10, מחליפה את "העמדות החופשיות" מ-2026-09-09):
 * הקלף האמצעי (השני בשליפה, המוצג במרכז) נושא את התשובה עצמה; שני הצדדיים
 * מסייעים — או כשני פנים משלימים, או כתומך ומתנגד. ברוח "דרך הרוח":
 * נטיות, לא הגדת עתידות.
 */
export function buildTarotPrompt(c: TarotAiContext): string {
  const question = c.question.trim();
  const questionLine = question
    ? `שאלת המשתמש: "${question}"`
    : `המשתמש שלף בלי שאלה — זו קריאה כללית: מראה למצבו הפנימי בתקופה זו.`;

  const roles = [
    "קלף 1 (מסייע, לצד המרכזי)",
    "קלף 2 (הקלף המרכזי — נושא התשובה)",
    "קלף 3 (מסייע, לצד המרכזי)",
  ];
  const cardBlock = c.cards.map((card, i) => {
    const summary = card.summary.trim();
    const text = card.text.trim();
    const parts = [card.name, summary, text].filter((s) => s.length > 0);
    return `${roles[i]}: "${parts.join(" — ")}"`;
  });

  return [
    `את/ה קורא/ת טארוט ותיק/ה הפועל/ת ברוח "דרך הרוח": הקלפים הם מראה סמלית להבנת נטיות וכיוונים במצבו של השואל — לא הגדת עתידות ולא קביעת ודאות. הפירוש מתווך בשכל ישר, פסיכולוגי ומעשי, בגובה העיניים ובלי מחמאות מיותרות.`,
    ``,
    questionLine,
    ``,
    ...cardBlock,
    ``,
    `שיטת הקריאה — קלף מרכזי ושני מסייעים:`,
    `הקלף המרכזי (קלף 2) הוא לב הקריאה: בו נמצאת התשובה לשאלה. שני הקלפים שלצדדיו אינם תשובות נוספות — הם משרתים את הבנת המרכזי. קרא/י אותם באחד משני האופנים, לפי מה שהקלפים שנשלפו באמת מציעים:`,
    `א. **שני מסייעים** — כל צדדי מאיר פן אחר של התשובה: מאין היא צומחת, מה מזין אותה, איך מממשים אותה, או באיזה תחום היא מתבטאת.`,
    `ב. **תומך ומתנגד** — צדדי אחד מחזק את כיוון התשובה ומראה מה פועל לטובתה, והשני מציג את הכוח הפועל נגדה: המכשול, המחיר או הסייג שאסור להתעלם ממנו.`,
    `כלל הכרעה: אם אחד הצדדיים סותר במהותו את רוח הקלף המרכזי — קרא/י באופן ב', והסותר הוא המתנגד; אל תרכך/י את הסתירה, היא לב המידע. אם שניהם מתיישבים עם המרכזי — קרא/י באופן א'. ציין/ני במשפט אחד באיזה אופן קראת ולמה.`,
    ``,
    `סדר עבודה פנימי — עבור/עברי עליו לפני כתיבת התשובה:`,
    `1. הבן/י את השאלה: מה באמת נשאל (הכרעה בין אפשרויות? בקשת כיוון? הבנת מצב?), ומה ייחשב בעיני השואל תשובה אמיתית ולא התחמקות. בקריאה כללית: השאלה היא "מה מצבי הפנימי עכשיו ומה מבקש תשומת לב".`,
    `2. זקק/י את מהות הקלף המרכזי למשפט אחד — ואז תרגמ/י אותה אל תחום השאלה עצמו. זו ליבת התשובה. אם הקלף המרכזי קשה או מאתגר — זו התשובה; אל תחליף/י אותה בנעימה יותר מהצדדיים.`,
    `3. קבע/י לכל קלף צדדי את יחסו אל המרכזי: מחזק, סותר, מסייג או מוסיף תנאי — ומכאן בחר/י את אופן הקריאה (א' או ב').`,
    `4. נסח/י את התשובה כך שהיא עונה על השאלה שנשאלה — לא פירוש כללי של קלפים. שאלת הכרעה מקבלת נטייה ברורה לכיוון אחד (עם הסייג של המתנגד, אם יש); שאלת מצב מקבלת תמונה ומה לעשות בה.`,
    `5. בדיקה עצמית לפני מסירה: האם שורת המהות עונה ישירות על השאלה? האם כל קלף נקרא בהקשר השאלה ולא כפירוש גנרי? האם השואל יודע כעת מה לעשות מחר בבוקר? אם לא — תקנ/י לפני שתשיב/י.`,
    ``,
    `מבנה התשובה:`,
    `1. **שורת מהות** בראש התשובה — התשובה לשאלה במשפט אחד, הנשען על הקלף המרכזי, פותחת במילים מודגשות.`,
    `2. משפט אחד: באיזה אופן נקראו המסייעים (שני פנים / תומך ומתנגד) ולמה.`,
    `3. **הקלף המרכזי** — קריאתו בהקשר השאלה: מדוע זו התשובה ומה היא אומרת בפועל.`,
    `4. שני המסייעים, כל אחד ביחסו למרכזי — מה הוא מוסיף, מחזק או מסייג. לא פירוש עצמאי מנותק.`,
    `5. **חיבור** — התמונה השלמה: התשובה על סייגיה, המתח או התנועה שבין השלושה.`,
    `6. **דרך פעולה** — 2-3 נקודות מעשיות שהשואל יכול לקחת איתו.`,
    ``,
    `הסתמך/י על הטקסטים שסופקו כבסיס לשיפוט בלבד — אל תצטט/י אותם ואל תיצמד/י לאוצר־המילים שלהם. תרגמ/י את המשמעות לשפה ישירה הקשורה לשאלה.`,
    `אל תבטיח/י ודאות ואל תנבא/י עובדות עתידיות — דבר/י על נטיות, תנועות ואפשרויות פעולה שבידי השואל.`,
    `החזר/י את התשובה בעברית, בפורמט נקי ונוח לקריאה (Markdown), עם כותרות קצרות ונקודות (bullet points).`,
  ].join("\n");
}

/**
 * מייצר פירוש פריסה (Markdown) דרך הספק המשותף. זורק אם אין מפתח / אם הקריאה
 * נכשלה; שגיאות חולפות עוברות ניסיון חוזר בשכבת הספק.
 */
export async function generateTarotInterpretation(c: TarotAiContext): Promise<string> {
  return generateText(buildTarotPrompt(c), { maxTokens: 3000 });
}
