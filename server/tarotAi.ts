import { generateText } from "./_core/aiProvider";

export interface TarotAiCard {
  /** שם אפקטיבי (override מה-DB או ברירת המחדל מ-shared). */
  name: string;
  /** שורת מהות קצרה מה-DB (יכולה להיות ריקה). */
  summary: string;
  /** הפירוש הסטטי כ-plain text (הקליינט ממיר מ-HTML). */
  text: string;
}

export interface TarotAiContext {
  /** יכולה להיות ריקה — שליפה בלי שאלה מותרת (קריאה כללית). */
  question: string;
  /** בדיוק 3, בסדר השליפה. */
  cards: TarotAiCard[];
}

/**
 * בונה את פרומפט קריאת הפריסה. טהורה — בלי רשת, בלי env.
 * העמדות חופשיות (החלטת 2026-09-09): לא מזריקים תפקידי עמדות — המודל בוחר
 * בעצמו מסגרת קריאה ומנמק אותה. ברוח "דרך הרוח": נטיות, לא הגדת עתידות.
 */
export function buildTarotPrompt(c: TarotAiContext): string {
  const question = c.question.trim();
  const questionLine = question
    ? `שאלת המשתמש: "${question}"`
    : `המשתמש שלף בלי שאלה — זו קריאה כללית: מראה למצבו הפנימי בתקופה זו.`;

  const cardBlock = c.cards.map((card, i) => {
    const summary = card.summary.trim();
    const text = card.text.trim();
    const parts = [card.name, summary, text].filter((s) => s.length > 0);
    return `קלף ${i + 1} (לפי סדר השליפה): "${parts.join(" — ")}"`;
  });

  return [
    `את/ה קורא/ת טארוט ותיק/ה הפועל/ת ברוח "דרך הרוח": הקלפים הם מראה סמלית להבנת נטיות וכיוונים במצבו של השואל — לא הגדת עתידות ולא קביעת ודאות. הפירוש מתווך בשכל ישר, פסיכולוגי ומעשי, בגובה העיניים ובלי מחמאות מיותרות.`,
    ``,
    questionLine,
    ``,
    ...cardBlock,
    ``,
    `לפניך שלושה קלפים ללא תפקידים קבועים. בחר/י בעצמך את הדרך הנכונה לקרוא אותם ביחס לשאלה (למשל: שורש–מצב–כיוון, מכשול–כוח–דרך, או כמהלך סיפורי אחד) — וציין/ני במשפט אחד איזו מסגרת בחרת ולמה דווקא היא.`,
    ``,
    `מבנה התשובה:`,
    `1. **שורת מהות** בראש התשובה — תמצית הקריאה ביחס לשאלה במשפט אחד, פותחת במילים מודגשות.`,
    `2. משפט המסגרת (איך בחרת לקרוא את השלושה ולמה).`,
    `3. קריאת כל קלף בתורו, בהקשר השאלה והמסגרת שבחרת — לא פירוש גנרי של הקלף.`,
    `4. **חיבור** — מה שלושת הקלפים אומרים יחד: המתח, התנועה או הסיפור שביניהם.`,
    `5. **דרך פעולה** — 2-3 נקודות מעשיות שהשואל יכול לקחת איתו.`,
    ``,
    `הסתמך/י על הטקסטים שסופקו כבסיס לשיפוט בלבד — אל תצטט/י אותם ואל תיצמד/י לאוצר־המילים שלהם. תרגמ/י את המשמעות לשפה ישירה הקשורה לשאלה.`,
    `אל תבטיח/י ודאות ואל תנבא/י עובדות עתידיות — דבר/י על נטיות, תנועות ואפשרויות פעולה שבידי השואל.`,
    `החזר/י את התשובה בעברית, בפורמט נקי ונוח לקריאה (Markdown), עם כותרות קצרות ונקודות (bullet points).`,
  ].join("\n");
}

/**
 * מייצר פירוש פריסה (Markdown) דרך הספק המשותף. זורק אם אין מפתח / אם הקריאה
 * נכשלה; שגיאות חולפות עוברות ניסיון חוזר בשכבת הספק.
 */
export async function generateTarotInterpretation(c: TarotAiContext): Promise<string> {
  return generateText(buildTarotPrompt(c), { maxTokens: 3000 });
}
